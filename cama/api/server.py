"""CAMA HTTP API — v1 application.

This is the v1 scaffold that implements the contract published in
``API.md``. Endpoint coverage in this file:

  GET   /v1/health
  POST  /v1/memories          (provenance enforced at boundary)
  GET   /v1/memories/{id}     (dyad-scoped)
  DELETE /v1/memories/{id}    (X-Confirm required)
  POST  /v1/search            (counterweight injection wired in)
  POST  /v1/thread/start
  GET   /v1/dyads/{id}
  GET   /v1/version
  GET   /v1/openapi.json      (auto-generated by FastAPI)

Endpoints NOT in v1 of this PR (listed in API.md § 13 as follow-up):
  PATCH /v1/memories/{id}/confirm   (consent token flow)
  POST  /v1/consent/{challenge,grant}
  PATCH /v1/dyads/{id}/consent
  DELETE /v1/dyads/{id}
  POST  /v1/thread/end
  GET   /v1/dyads/{id}/export

Running locally::

    pip install "cama[api]"
    export CAMA_DB_PATH=/path/to/memory.db
    export CAMA_API_KEY_DB=/path/to/api_keys.db
    export CAMA_ALLOWED_ORIGINS=https://app.example.com
    cama-api-server --host 0.0.0.0 --port 8080
"""

